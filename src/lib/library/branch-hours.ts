/** Open/closed status of a branch now, or null when its hours are unknown. */
export function branchStatus(branch: number, now: Date = new Date()): OpenStatus | null {
  const week = BRANCH_HOURS[branch];
  if (!week) return null;
  const closed = BRANCH_CLOSED_NOTE[branch];
  if (closed) return { open: false, closingSoon: false, label: closed, today: "nieczynne" };
  return openStatus(week, now);
}
